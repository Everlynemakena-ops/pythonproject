#Arithmetic operators -Simple calculation
x = 90
y = 5

print( x + y)
print( x - y)
print( x * y)
print( x / y)
print( x % y) #Modulus -divides and gives the reminder as the answer

#Comparison Operators- compare values and gives a boolean
num1 = 45
num2 = 20

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2) #Equal to
print(num1 != num2) #Not Equal to

#Assignment Operators - Assign/Store value in variables
number = 80
print(number)


#operator precedence
number +=2
number -=3
print(number)
print(number)

#Logical Operators -and, or, not
print( 100 == 50 and 60 < 80 )
print( 100 == 50 or 60 < 80 )
print( not(100 == 50 and 60 < 80) )
